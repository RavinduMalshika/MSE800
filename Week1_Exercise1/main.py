print("Calculate sum and product of two numbers")

# take user input and store in variables of type float
number1 = float(input("Please enter number 1 value: "))
number2 = float(input("Please enter number 2 value: "))

# find the sum of the 2 numbers
sum = number1 + number2

# find the product of the 2 numbers
product = number1 * number2

# display the results
print("The sum of the numbers is", sum)
print("The product of the numbers is", product)
